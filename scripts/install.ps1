# Mugon Editor installer for Windows.
#
#   irm <release-link>/install.ps1 | iex
#   .\install.ps1 [-Dir $env:USERPROFILE\.mugon\editor] [-Version 0.1.0]
#
# Downloads the Windows archive of a GitLab release and unpacks it. For private projects set $env:GITLAB_TOKEN
# (a token with read_api scope). MUGON_EDITOR_API_URL / MUGON_EDITOR_PROJECT_ID override the values filled in by the release job.
param(
    [string]$Dir = (Join-Path $env:USERPROFILE ".mugon\editor"),
    [string]$Version = "latest"
)
$ErrorActionPreference = "Stop"
$api = if ($env:MUGON_EDITOR_API_URL) { $env:MUGON_EDITOR_API_URL } else { "@API_URL@" }
$project = if ($env:MUGON_EDITOR_PROJECT_ID) { $env:MUGON_EDITOR_PROJECT_ID } else { "@PROJECT_ID@" }
if ($api -like "@*" -or $project -like "@*") { throw "Set MUGON_EDITOR_API_URL and MUGON_EDITOR_PROJECT_ID (this copy was not generated by the release job)." }
$headers = @{}
if ($env:GITLAB_TOKEN) { $headers["PRIVATE-TOKEN"] = $env:GITLAB_TOKEN }

if ($Version -eq "latest") {
    $release = (Invoke-RestMethod -Headers $headers -Uri "$api/projects/$project/releases?per_page=1")[0]
} else {
    $release = Invoke-RestMethod -Headers $headers -Uri "$api/projects/$project/releases/v$($Version.TrimStart('v'))"
}
$link = $release.assets.links | Where-Object { $_.name -like "*windows-x86_64.zip" } | Select-Object -First 1
if (-not $link) { throw "Release $($release.tag_name) has no Windows archive." }

$zip = Join-Path ([IO.Path]::GetTempPath()) "mugon-editor-$($release.tag_name).zip"
Write-Host "Downloading $($link.name) ($($release.tag_name))..."
Invoke-WebRequest -Headers $headers -Uri $link.url -OutFile $zip

$tmp = Join-Path ([IO.Path]::GetTempPath()) "mugon-editor-extract"
if (Test-Path $tmp) { Remove-Item -Recurse -Force $tmp }
Expand-Archive -Path $zip -DestinationPath $tmp -Force
New-Item -ItemType Directory -Force $Dir | Out-Null
Copy-Item -Recurse -Force (Join-Path $tmp "mugon-editor\*") $Dir
Remove-Item -Recurse -Force $tmp, $zip

$userPath = [Environment]::GetEnvironmentVariable("Path", "User")
if (($userPath -split ";") -notcontains $Dir) {
    [Environment]::SetEnvironmentVariable("Path", "$userPath;$Dir", "User")
    Write-Host "Added $Dir to your user PATH (open a new terminal)."
}
Write-Host "Installed Mugon Editor $($release.tag_name) to $Dir"
Write-Host "Next: run 'mugon-editor --help'."
