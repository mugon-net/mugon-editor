#!/usr/bin/env bash
# Mugon Editor installer for Linux (x86_64).
#
#   curl -fsSL <release-link>/install.sh | bash
#   ./install.sh [--dir ~/.mugon/editor] [--version 0.1.0]
#
# For private projects export GITLAB_TOKEN (read_api scope). MUGON_EDITOR_API_URL / MUGON_EDITOR_PROJECT_ID override the values
# filled in by the release job.
set -euo pipefail

api="${MUGON_EDITOR_API_URL:-@API_URL@}"
project="${MUGON_EDITOR_PROJECT_ID:-@PROJECT_ID@}"
dir="${HOME}/.mugon/editor"
version="latest"
while [ $# -gt 0 ]; do
  case "$1" in
    --dir) dir="$2"; shift 2 ;;
    --version) version="${2#v}"; shift 2 ;;
    *) echo "unknown argument: $1" >&2; exit 1 ;;
  esac
done
case "$api$project" in *@*) echo "Set MUGON_EDITOR_API_URL and MUGON_EDITOR_PROJECT_ID (this copy was not generated by the release job)." >&2; exit 1 ;; esac

auth=()
[ -n "${GITLAB_TOKEN:-}" ] && auth=(-H "PRIVATE-TOKEN: ${GITLAB_TOKEN}")

if [ "$version" = "latest" ]; then
  json="$(curl -fsSL "${auth[@]}" "${api}/projects/${project}/releases?per_page=1")"
else
  json="$(curl -fsSL "${auth[@]}" "${api}/projects/${project}/releases/v${version}")"
fi
url="$(printf '%s' "$json" | grep -o '"url":"[^"]*linux-x86_64\.tar\.gz"' | head -1 | cut -d'"' -f4 || true)"
[ -n "$url" ] || { echo "No Linux archive found in the release." >&2; exit 1; }

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
echo "Downloading ${url##*/}..."
curl -fsSL "${auth[@]}" -o "$tmp/mugon-editor.tar.gz" "$url"
mkdir -p "$dir"
tar -xzf "$tmp/mugon-editor.tar.gz" -C "$tmp"
cp -r "$tmp/mugon-editor/." "$dir/"

mkdir -p "$HOME/.local/bin"
for exe in mugon-editor mugon-editor-thumbs mugon-editor-app; do
  ln -sf "$dir/$exe" "$HOME/.local/bin/$exe"
done
echo "Installed Mugon Editor to $dir (symlinks in ~/.local/bin; make sure it is on your PATH)."
echo "Next: run 'mugon-editor --help'."
echo "The editor and thumbnail renderer need a Vulkan-capable GPU driver."
