//! BSN export and asset bundling.
//!
//! Bevy 0.19 has no `.bsn` file format yet (BSN is the `bsn!` macro), so the export is a Rust source file
//! with one function returning `impl SceneList`. Models stay separate glTF files that the scene references
//! by asset path, and `bundle` copies exactly those files (plus their textures) into the game's asset folder.
//! Marker entities export as `Transform` (scale = size) plus `Marker { shape: MarkerShape::.. }`; those two types come
//! from `mugon_sdk_bevy::scene`, which exported scenes import themselves. Every entity gets an explicit `Transform` and
//! `Visibility`, and each file ends with a `spawn(world)` function.

use crate::components::ComponentRegistry;
use crate::game::{scene_identifier, GameConfig};
use crate::{Project, SceneEntity, Xform};
use anyhow::{bail, Result};
use mugon_editor_core::index::Index;
use serde::Serialize;
use std::collections::{BTreeSet, HashMap, HashSet};
use std::path::{Path, PathBuf};

pub struct ExportOptions {
    /// Name of the generated function.
    pub fn_name: String,
    /// Prefix of every asset path, e.g. `synty/` (the folder inside the game's asset dir). Empty or ending in `/`.
    pub asset_prefix: String,
    /// Extra `use` paths so the game's components resolve, e.g. `crate::components::*`.
    pub uses: Vec<String>,
}

impl Default for ExportOptions {
    fn default() -> Self {
        Self { fn_name: "scene".into(), asset_prefix: String::new(), uses: Vec::new() }
    }
}

fn identifier(name: &str) -> String {
    let mut s: String = name.chars().map(|c| if c.is_ascii_alphanumeric() || c == '_' { c } else { '_' }).collect();
    if s.is_empty() || s.chars().next().unwrap().is_ascii_digit() {
        s.insert(0, '_');
    }
    s
}

fn float(x: f32) -> String {
    let s = format!("{x}");
    if s.contains('.') || s.contains('e') || s.contains("inf") || s.contains("NaN") {
        s
    } else {
        format!("{s}.0")
    }
}

fn transform_expr(t: &Xform) -> Option<String> {
    let d = Xform::default();
    let mut fields = Vec::new();
    if t.translation != d.translation {
        fields.push(format!("translation: Vec3::new({}, {}, {})", float(t.translation[0]), float(t.translation[1]), float(t.translation[2])));
    }
    if t.rotation != d.rotation {
        fields.push(format!("rotation: Quat::from_xyzw({}, {}, {}, {})", float(t.rotation[0]), float(t.rotation[1]), float(t.rotation[2]), float(t.rotation[3])));
    }
    if t.scale != d.scale {
        fields.push(format!("scale: Vec3::new({}, {}, {})", float(t.scale[0]), float(t.scale[1]), float(t.scale[2])));
    }
    if fields.is_empty() {
        None
    } else {
        Some(format!("Transform {{ {} }}", fields.join(", ")))
    }
}

pub fn asset_path(prefix: &str, asset: &mugon_editor_core::Asset) -> String {
    format!("{prefix}{}/{}", asset.pack, asset.model)
}

/// Generates the Rust source containing the `bsn_list!` for the whole project.
pub fn export_bsn(project: &Project, index: &Index, registry: &ComponentRegistry, opts: &ExportOptions) -> Result<String> {
    // unique, valid `#Name`s
    let mut names: HashMap<u64, String> = HashMap::new();
    let mut taken: HashSet<String> = HashSet::new();
    for e in &project.entities {
        let base = identifier(&e.name);
        let mut name = base.clone();
        let mut n = 1;
        while !taken.insert(name.clone()) {
            n += 1;
            name = format!("{base}_{n}");
        }
        names.insert(e.id, name);
    }

    let mut out = String::new();
    out.push_str("// Generated by Mugon Editor. Do not edit by hand; re-export from the editor.\n");
    out.push_str(&format!("// Project: {}\n", project.name));
    out.push_str("use bevy::prelude::*;\n");
    if project.entities.iter().any(|e| e.marker.is_some()) {
        out.push_str("use mugon_sdk_bevy::scene::{Marker, MarkerShape};\n");
    }
    for u in &opts.uses {
        out.push_str(&format!("use {u};\n"));
    }
    out.push('\n');
    let fn_name = identifier(&opts.fn_name);
    out.push_str(&format!("pub fn {fn_name}() -> impl SceneList {{\n    bsn_list![\n"));
    let roots: Vec<&SceneEntity> = project.children(None).collect();
    for r in roots {
        write_entity(project, index, registry, opts, &names, r, 2, &mut out)?;
        out.push_str(",\n");
    }
    out.push_str("    ]\n}\n");
    out.push_str(&format!(
        "\n/// Spawns the whole scene; returns the root entities.\npub fn spawn(world: &mut World) -> Result<Vec<Entity>, bevy::scene::SpawnSceneError> {{\n    world.spawn_scene_list({fn_name}())\n}}\n"
    ));
    Ok(out)
}

#[allow(clippy::too_many_arguments)]
fn write_entity(
    project: &Project,
    index: &Index,
    registry: &ComponentRegistry,
    opts: &ExportOptions,
    names: &HashMap<u64, String>,
    e: &SceneEntity,
    depth: usize,
    out: &mut String,
) -> Result<()> {
    let pad = "    ".repeat(depth);
    let inner = "    ".repeat(depth + 1);
    out.push_str(&format!("{pad}(\n{inner}#{}\n", names[&e.id]));
    // Always explicit, even for the identity: transform/visibility propagation (and avian's collider scale
    // propagation) skip a subtree whose root lacks these.
    let transform = transform_expr(&e.transform).unwrap_or_else(|| "Transform".to_string());
    out.push_str(&format!("{inner}{transform}\n{inner}Visibility\n"));
    if let Some(id) = &e.asset {
        let Some(asset) = index.get(id) else { bail!("entity '{}' references unknown asset '{id}'", e.name) };
        out.push_str(&format!("{inner}WorldAssetRoot({:?})\n", format!("{}#Scene0", asset_path(&opts.asset_prefix, asset))));
    }
    if let Some(shape) = e.marker {
        // the volume is the unit shape scaled by the Transform above
        out.push_str(&format!("{inner}Marker {{ shape: MarkerShape::{} }}
", shape.variant()));
    }
    for c in &e.components {
        let Some(def) = registry.get(&c.name) else { bail!("entity '{}' uses unknown component '{}'", e.name, c.name) };
        let fields: Vec<String> = def
            .fields
            .iter()
            .map(|f| {
                let v = c.values.get(&f.name).cloned().unwrap_or_else(|| f.default_value());
                format!("{}: {}", f.name, f.rust_expr(&v))
            })
            .collect();
        if fields.is_empty() {
            out.push_str(&format!("{inner}{}\n", c.name));
        } else {
            out.push_str(&format!("{inner}{} {{ {} }}\n", c.name, fields.join(", ")));
        }
    }
    let kids: Vec<&SceneEntity> = project.children(Some(e.id)).collect();
    if !kids.is_empty() {
        out.push_str(&format!("{inner}Children [\n"));
        for k in kids {
            write_entity(project, index, registry, opts, names, k, depth + 2, out)?;
            out.push_str(",\n");
        }
        out.push_str(&format!("{inner}]\n"));
    }
    out.push_str(&format!("{pad})"));
    Ok(())
}

#[derive(Debug, Serialize)]
pub struct BundleFile {
    pub path: String,
    pub bytes: u64,
}

#[derive(Debug, Serialize, Default)]
pub struct BundleReport {
    pub files: Vec<BundleFile>,
    pub total_bytes: u64,
}

/// Copies the glTFs (with buffers) and textures used by the project into `out_dir`, keeping the library's
/// `<prefix><pack>/...` layout so the glTFs' relative texture paths keep working. Writes `manifest.json`.
pub fn bundle(project: &Project, index: &Index, out_dir: &Path, asset_prefix: &str) -> Result<BundleReport> {
    let mut copies: BTreeSet<(String, String)> = BTreeSet::new(); // (pack, relative path)
    for id in project.entities.iter().filter_map(|e| e.asset.as_ref()).collect::<BTreeSet<_>>() {
        let Some(asset) = index.get(id) else { bail!("unknown asset '{id}'") };
        let model_dir = Path::new(&asset.model).parent().map(|p| p.to_path_buf()).unwrap_or_default();
        let src_dir = index.root.join(&asset.pack).join(&model_dir);
        for entry in std::fs::read_dir(&src_dir)? {
            let entry = entry?;
            if entry.path().is_file() {
                copies.insert((asset.pack.clone(), mugon_editor_core::to_slash(&model_dir.join(entry.file_name()))));
            }
        }
        if let Some(t) = &asset.texture {
            copies.insert((asset.pack.clone(), t.clone()));
        }
    }
    let mut report = BundleReport::default();
    for (pack, rel) in copies {
        let src = index.root.join(&pack).join(&rel);
        let published = format!("{asset_prefix}{pack}/{rel}");
        let dest = out_dir.join(&published);
        std::fs::create_dir_all(dest.parent().unwrap())?;
        let bytes = std::fs::copy(&src, &dest)?;
        report.total_bytes += bytes;
        report.files.push(BundleFile { path: published, bytes });
    }
    std::fs::create_dir_all(out_dir)?;
    std::fs::write(out_dir.join("manifest.json"), serde_json::to_string_pretty(&report)?)?;
    Ok(report)
}

pub struct GameExport {
    pub bsn_path: PathBuf,
    pub bundle: BundleReport,
}

/// Writes the scene's BSN into the game's BSN folder as `<scene>.rs` and copies the used assets into the game's
/// asset folder (`<assets>/<pack>/...`).
pub fn export_to_game(project: &Project, index: &Index, registry: &ComponentRegistry, game: &GameConfig, scene_name: &str) -> Result<GameExport> {
    let fn_name = scene_identifier(scene_name);
    let options = ExportOptions { fn_name: fn_name.clone(), asset_prefix: String::new(), uses: game.bsn_uses.clone() };
    let source = export_bsn(project, index, registry, &options)?;
    std::fs::create_dir_all(&game.scenes_bsn_dir)?;
    let bsn_path = game.scenes_bsn_dir.join(format!("{fn_name}.rs"));
    std::fs::write(&bsn_path, source)?;
    let bundle = bundle(project, index, &game.assets_dir, "")?;
    Ok(GameExport { bsn_path, bundle })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ComponentInstance;
    use mugon_editor_core::{Asset, Library, Pack};
    use serde_json::json;
    use std::collections::BTreeMap;

    fn fixture() -> (std::path::PathBuf, Index) {
        let root = std::env::temp_dir().join(format!("mugon-editor-export-test-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        let pack_dir = root.join("P");
        std::fs::create_dir_all(pack_dir.join("models/Crate")).unwrap();
        std::fs::create_dir_all(pack_dir.join("textures")).unwrap();
        std::fs::write(pack_dir.join("models/Crate/Crate.gltf"), "{}").unwrap();
        std::fs::write(pack_dir.join("models/Crate/buffer.bin"), "bin").unwrap();
        std::fs::write(pack_dir.join("textures/Atlas.png"), "png").unwrap();
        let asset = Asset { id: "P/Crate".into(), name: "Crate".into(), model: "models/Crate/Crate.gltf".into(), texture: Some("textures/Atlas.png".into()), ..Default::default() };
        Pack { id: "P".into(), name: "P".into(), assets: vec![asset], ..Default::default() }.save(&pack_dir).unwrap();
        let index = Index::load(&Library::new(&root)).unwrap();
        (root, index)
    }

    #[test]
    fn exports_into_the_game_folders() {
        let (root, index) = fixture();
        let game_dir = root.join("game");
        let text = "[editor.scenes]\nbsn-use = [\"crate::components::*\"]\n";
        let game = GameConfig::from_toml(&game_dir, text, Path::new("mugon.toml")).unwrap();
        let mut project = Project::default();
        project.add("Crate", Some("P/Crate".into()), Xform::default(), None);
        let out = export_to_game(&project, &index, &ComponentRegistry::default(), &game, "Level One").unwrap();
        assert_eq!(out.bsn_path, game_dir.join("src/scenes/level_one.rs"));
        let source = std::fs::read_to_string(&out.bsn_path).unwrap();
        assert!(source.contains("pub fn level_one()") && source.contains("use crate::components::*;"), "{source}");
        assert!(source.contains("pub fn spawn(world: &mut World)") && source.contains("world.spawn_scene_list(level_one())"), "{source}");
        assert!(source.contains("WorldAssetRoot(\"P/models/Crate/Crate.gltf#Scene0\")"));
        assert!(game_dir.join("assets/P/models/Crate/Crate.gltf").is_file());
        assert!(game_dir.join("assets/P/textures/Atlas.png").is_file());
    }

    #[test]
    fn exports_and_bundles() {
        let (root, index) = fixture();
        let registry = crate::game::example_registry();
        let mut p = Project::default();
        let a = p.add("Crate 1", Some("P/Crate".into()), Xform { translation: [1.0, 0.0, 2.5], ..Default::default() }, None);
        let b = p.add("Crate 1", Some("P/Crate".into()), Xform::default(), Some(a));
        p.get_mut(b).unwrap().components.push(ComponentInstance { name: "Health".into(), values: BTreeMap::from([("max".into(), json!(40))]) });
        p.get_mut(b).unwrap().components.push(ComponentInstance { name: "Pickup".into(), values: BTreeMap::new() });

        let m = p.add_marker("Spawn Zone", crate::MarkerShape::Sphere, Xform { translation: [0.0, 1.0, 0.0], scale: [4.0, 4.0, 4.0], ..Default::default() }, None);
        p.get_mut(m).unwrap().components.push(ComponentInstance { name: "Pickup".into(), values: BTreeMap::new() });

        let src = export_bsn(&p, &index, &registry, &ExportOptions { fn_name: "level_one".into(), asset_prefix: "synty/".into(), uses: vec!["crate::*".into()] }).unwrap();
        assert!(src.contains("pub fn level_one() -> impl SceneList"));
        assert!(src.contains("#Crate_1\n"));
        assert!(src.contains("#Crate_1_2\n"));
        assert!(src.contains("Transform { translation: Vec3::new(1.0, 0.0, 2.5) }"));
        assert!(src.contains("use mugon_sdk_bevy::scene::{Marker, MarkerShape};"));
        assert!(src.contains("#Crate_1_2\n                    Transform\n                    Visibility\n"), "identity transform and visibility are explicit: {src}");
        assert!(src.contains("WorldAssetRoot(\"synty/P/models/Crate/Crate.gltf#Scene0\")"));
        assert!(src.contains("Health { max: 40.0 }"));
        assert!(src.contains("Children ["));
        assert!(src.contains("#Spawn_Zone
"));
        assert!(src.contains("Marker { shape: MarkerShape::Sphere }"));
        assert!(src.contains("Transform { translation: Vec3::new(0.0, 1.0, 0.0), scale: Vec3::new(4.0, 4.0, 4.0) }"));

        // golden file compiled by the mugon-editor-bsn-check crate
        let golden = Path::new("../mugon-editor-bsn-check/src/level.rs");
        if std::env::var("UPDATE_GOLDEN").is_ok() {
            std::fs::write(golden, &src).unwrap();
        }
        let on_disk = std::fs::read_to_string(golden).unwrap().replace("
", "
");
        assert_eq!(on_disk, src, "golden BSN out of date; run with UPDATE_GOLDEN=1");

        let out = root.join("game_assets");
        let report = bundle(&p, &index, &out, "synty/").unwrap();
        assert_eq!(report.files.len(), 3);
        assert!(out.join("synty/P/models/Crate/buffer.bin").is_file());
        assert!(out.join("synty/P/textures/Atlas.png").is_file());
        assert!(out.join("manifest.json").is_file());
    }
}
